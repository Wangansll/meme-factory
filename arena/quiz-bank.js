// 打乱选项顺序（服务端组题时执行，保证答案位置随机）
function shuffledQuestion(q) {
  const idx = [0, 1, 2, 3];
  for (let i = idx.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [idx[i], idx[j]] = [idx[j], idx[i]];
  }
  return {
    q: q.q,
    o: idx.map(k => q.o[k]),
    a: idx.indexOf(q.a),
    c: q.c,
    w: q.w
  };
}

